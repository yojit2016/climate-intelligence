LOGGER = logging.getLogger(__name__)
cached_history = st.cache_data(ttl=HISTORY_TTL, max_entries=24, show_spinner=False)(load_history)
cached_acquisition = st.cache_data(ttl=HISTORY_TTL, max_entries=4, show_spinner=False)(acquire_supported)


@st.cache_data(ttl=CURRENT_TTL, max_entries=12, show_spinner=False)
def live_weather(city_name: str, force_refresh: bool = False):
    return load_current(city_name, force_refresh=force_refresh)


def refresh_weather():
    """Invalidate only weather/model caches; the next acquisition bypasses disk."""
    from climate.forecast_panel import cached_model
    cached_history.clear()
    cached_acquisition.clear()
    live_weather.clear()
    cached_model.clear()
    st.session_state["refresh_current"] = True
    st.session_state["refresh_training"] = True
    st.session_state["refresh_history"] = True
    st.session_state["refresh_chart_cities"] = list(CITIES)


def display_value(value, suffix: str = " °C") -> str:
    try:
        number = float(value)
        return f"{number:.1f}{suffix}" if math.isfinite(number) else "Unavailable"
    except (ValueError, TypeError):
        return "Unavailable"


def filters():
    today = local_today(CITIES["Delhi"])
    with st.sidebar:
        st.markdown("### Climate Intelligence")
        st.caption("INDIA / TEMPERATURE MONITORING")
        with st.form("filters"):
            city = st.selectbox("Primary city", list(CITIES), index=1)
            dates = st.date_input("Historical date range", value=training_period(today),
                                  min_value=pd.Timestamp("1940-01-01").date(), max_value=today - timedelta(days=1))
            with st.expander("Optional analysis controls"):
                threshold = st.number_input("Exploratory threshold (°C)", min_value=20., max_value=60., value=40., step=.5)
                smoothing = st.checkbox("Show signal smoothing", value=False)
                window = st.select_slider("Smoothing window (days)", options=[5, 7, 11, 15], value=7)
                comparison = st.multiselect("Comparison cities", list(CITIES), default=["Mumbai", "Pune"])
            st.form_submit_button("Apply filters", type="primary", width="stretch")
        st.button("Refresh weather data", on_click=refresh_weather, width="stretch")
        st.caption("Refresh downloads fresh history for all six cities, current conditions, and model results. Current conditions also update every 15 minutes while this dashboard is open.")
        st.caption("Thresholds support exploration and are not official heatwave warnings.")
    if not isinstance(dates, (tuple, list)) or len(dates) != 2:
        st.info("Select both the beginning and end of the historical range.")
        st.stop()
    start, end = dates
    if (end - start).days > 3653:
        st.error("Select at most ten years per request to keep downloads and training responsive.")
        st.stop()
    return city, start, end, threshold, smoothing, window, comparison


@st.fragment(run_every=timedelta(seconds=CURRENT_TTL))
def current_cards(city: str):
    try:
        refresh = st.session_state.pop("refresh_current", False)
        current, forecast = live_weather(city, force_refresh=refresh)
        left, right = st.columns(2)
        left.metric("Current temperature · model estimate", display_value(current.get("temperature_2m")))
        right.metric("Current relative humidity · model estimate", display_value(current.get("relative_humidity_2m"), " %"))
        st.caption(f"Open-Meteo current estimate at {current.get('time', 'unavailable')} · Asia/Kolkata. No station measurements are ingested.")
        st.caption("Automatically checks for new current weather every 15 minutes while open. Current conditions and provider forecasts are model output.")
        with st.expander("Open-Meteo forecast · separate provider product"):
            st.caption("Provider weather model output, not predictions generated by the local Random Forest. This panel refreshes with current conditions.")
            st.plotly_chart(range_chart(forecast), width="stretch")
            chart_story(forecast, "Open-Meteo's weather models provide these daily maximum, minimum and mean estimates; they are separate from our Random Forest.",
                        peak_observation(forecast), "These are provider forecasts for the dates shown, not observations or outputs from the local model. Refresh timing does not guarantee forecast accuracy.")
            st.dataframe(forecast[["date", "tmax", "tmin", "tmean", "source"]], hide_index=True, width="stretch")
    except (WeatherError, ValueError, OSError) as exc:
        st.warning(f"Current conditions unavailable: {exc}")
        st.caption("Use Refresh weather data to retry now; automatic current checks continue every 15 minutes while open.")


@st.fragment(run_every=timedelta(seconds=HISTORY_TTL))
def automatic_training(city: str):
    today = local_today(CITIES[city])
    refresh = st.session_state.pop("refresh_training", False)
    with st.spinner("Acquiring three years of historical weather for all supported cities…"):
        acquired = cached_acquisition(today, force_refresh=refresh)
    st.caption(f"Automatic training history: {acquired.start:%d %b %Y} – {acquired.end:%d %b %Y}. Independent of chart date filters; checked every six hours while open.")
    status = []
    for name in CITIES:
        dataset = acquired.datasets.get(name)
        status.append({"City": name, "Status": "Available" if dataset else "Unavailable",
                       "Valid daily maxima": int(dataset[1].tmax.notna().sum()) if dataset else 0})
    with st.expander("Automatic acquisition status · all supported cities"):
        st.dataframe(pd.DataFrame(status), hide_index=True, width="stretch")
    for name, error in acquired.errors.items():
        st.warning(f"{name} automatic download unavailable: {error}. Refresh weather data to retry.")
    if city in acquired.datasets:
        forecast_panel(acquired.datasets[city][1])
    else:
        st.info("Local ML predictions unavailable because historical acquisition failed for this city. No substitute data or predictions are used.")


def render():
    st.set_page_config(page_title="Climate Intelligence", layout="wide")
    st.markdown(CSS, unsafe_allow_html=True)
    workspace = st.sidebar.radio("Data workspace", ["Open-Meteo point estimates", "IMD gridded temperature"], key="data_workspace")
    if workspace == "IMD gridded temperature":
        from climate.imd_ui import render_imd
        render_imd()
        return
    city, start, end, threshold, smoothing, window, comparison = filters()
    st.title("Climate Intelligence")
    st.caption(f"{city} · {start:%d %b %Y} — {end:%d %b %Y} · All temperatures in °C")
    st.caption("Open-Meteo · modeled / reanalysis estimates at city locations. Use the sidebar to switch to official IMD grids. Thresholds are exploratory, not official warnings.")
    overview, historical, prediction, data = st.tabs(SECTIONS)
    with overview:
        st.subheader("What is happening with temperatures?")
        current_cards(city)
    refresh_history = st.session_state.pop("refresh_history", False)
    pending_refresh = st.session_state.get("refresh_chart_cities", [])
    try:
        with st.spinner("Loading historical weather…"):
            raw, frame, report = cached_history(city, start, end, force_refresh=refresh_history or city in pending_refresh)
        if city in pending_refresh:
            pending_refresh.remove(city)
            st.session_state["refresh_chart_cities"] = pending_refresh
    except (WeatherError, ValueError, OSError) as exc:
        LOGGER.exception("History unavailable")
        with overview:
            st.error(f"Historical data unavailable: {exc}")
            st.info("Use Refresh weather data to retry. Current weather and training history are acquired independently.")
        with historical:
            st.info("Historical charts need a successful download for the selected city and dates.")
        with prediction:
            automatic_training(city)
        with data:
            st.info("A processing summary will appear after historical data is available.")
        st.stop()
    stats = summary(frame, threshold)
    with overview:
        st.subheader("Your selected historical period")
        columns = st.columns(4)
        for column, label, value in zip(columns,
                ["Average daily maximum", "Highest daily maximum", "Lowest daily minimum", "Days above exploratory threshold"],
                [display_value(stats["mean_max"]), display_value(stats["highest"]),
                 display_value(stats["lowest"]), str(stats["exceedance_days"]) if stats["valid_days"] else "Unavailable"]):
            column.metric(label, value)
        st.write(peak_observation(frame))
        st.caption(f"{stats['valid_days']} valid daily maxima · {stats['missing_days']} missing daily maxima. An average daily maximum describes daytime peaks, not the average temperature across each full day.")
        if stats["missing_days"]:
            st.info("This period has missing daily maxima. Summaries use available values and cannot establish complete coverage.")
    with historical:
        st.subheader("How do temperatures vary over time and between cities?")
        view = st.radio("Explore history", ["Daily temperatures", "Monthly & seasonal", "Across cities"], horizontal=True)
        if view == "Daily temperatures":
            trends_panel(frame, threshold, smoothing, window)
        elif view == "Monthly & seasonal":
            patterns_panel(frame)
        else:
            def comparison_history(name, first, last):
                result = cached_history(name, first, last, force_refresh=refresh_history or name in pending_refresh)
                if name in pending_refresh:
                    pending_refresh.remove(name)
                    st.session_state["refresh_chart_cities"] = pending_refresh
                return result
            regional_panel(frame, comparison, start, end, threshold, comparison_history)
    with prediction:
        automatic_training(city)
    with data:
        st.subheader("Where did this data come from, and what changed?")
        st.caption("This summary describes the historical chart dataset selected in the sidebar. Current conditions, provider forecasts and the model's independent three-year training history are separate products.")
        processing_table(point_processing_summary(raw, frame, report, smoothing=smoothing, window=window))
        st.write("Processing: normalize dates to Asia/Kolkata → remove invalid dates and duplicate city-days → replace impossible or inconsistent temperatures with missing values → add missing calendar dates → cache raw and processed tables separately.")
        st.caption("No missing temperatures are filled. Optional smoothing is a chart-only view; the source values and ML inputs remain unchanged. Invalid-row counts describe distinct raw rows; missing counts describe processed values, so these counts are not a partition of acquired rows.")
        with st.expander("Detailed processing report and source labels"):
            st.json(report)
            st.dataframe(frame.groupby("source").size().rename("Days"), width="stretch")
            st.caption("The original invalid_values_or_rows report counts mixed value/row events, not distinct records. The summary above counts distinct flagged raw records. Historical caches expire after 6 hours; current estimates after 15 minutes.")
        with st.expander("Inspect processed records"):
            st.dataframe(frame, width="stretch", hide_index=True)
        left, right = st.columns(2)
        filename = f"{city.lower()}_{start}_{end}"
        left.download_button("Download processed CSV", csv_bytes(frame), f"{filename}_processed.csv", "text/csv")
        right.download_button("Download raw API table CSV", csv_bytes(raw), f"{filename}_raw.csv", "text/csv")
        st.caption("Exports retain source labels and timezone offsets. Raw tables preserve API nulls and precede quality controls; missing processed values remain blank.")
    st.caption("Weather data: [Open-Meteo](https://open-meteo.com/) · [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/) · Analytics and forecasts are exploratory.")
